"""
deployment_package.py - one-click Jetson Nano deployment package
=================================================================

Builds ``bb8_jetson_package_<timestamp>.zip`` containing everything the robot needs:

    bb8_jetson/
      robot_hw_config.json      <- GENERATED from the simulator config (geometry can no longer drift)
      jetson_control_loop.py    <- Python runner (ONNX Runtime / C++ .so / classical / --test modes)
      jetson_control_loop.cpp, CMakeLists.txt
      classical_controller.py, classical_params.json
      arduino_nano33iot_imu_i2c/arduino_nano33iot_imu_i2c.ino
      policy/      best_policy.onnx, best_policy.json, cpp/bb8_policy_inference.{cpp,h}
      classical/   cpp/bb8_policy_inference.{cpp,h}   (same API -> build with -DPOLICY_DIR=classical/cpp)
      DEPLOY.md    exact commands for this package

Hardware-specific fields of an existing ``robot_hw_config.json`` (I2C addresses, UART ports,
GPIO lines, direction signs, TMC currents) are preserved; only geometry / timing / limits are
overwritten from the simulator configuration.
"""
from __future__ import annotations

import json
import math
import os
import shutil
import tempfile
import zipfile
from typing import Dict, Optional

from config_and_distributions import AppConfig, timestamp

HERE = os.path.dirname(os.path.abspath(__file__))
DEPLOY_DIR = os.path.join(HERE, "deployment_jetson")


def _base_dir() -> str:
    import sys
    if getattr(sys, "frozen", False):  # PyInstaller: data files live in _MEIPASS
        return getattr(sys, "_MEIPASS", HERE)
    return HERE


def hw_config_from_app(cfg: AppConfig, base: Optional[dict] = None) -> dict:
    """Merge simulator geometry into a hardware config dict."""
    if base is None:
        p = os.path.join(_base_dir(), "deployment_jetson", "robot_hw_config.json")
        base = json.load(open(p)) if os.path.isfile(p) else {}
    rc, ep = cfg.robot, cfg.episode
    out = dict(base)
    out.update({
        "_comment": "GENERATED by BB-8 RL Suite from the simulator config. Geometry/timing/limits come from the "
                    "simulator; hardware wiring fields (I2C, UART, GPIO, signs, currents) were preserved.",
        "control_hz": float(rc.control_hz),
        "ball_radius_m": float(rc.ball_radius_m),
        "wheel_radius_m": float(rc.wheel_radius_m),
        "zenith_angle_deg": float(rc.zenith_angle_deg),
        "wheel_azimuths_deg": [float(a) for a in rc.wheel_azimuths_deg],
        "max_wheel_speed_rads": float(rc.stepper_max_speed_rads),
        "full_steps_per_rev": int(rc.stepper_full_steps_per_rev),
        "microsteps": int(rc.tmc2208_microsteps),
        "tilt_cutoff_deg": float(min(ep.fall_tilt_deg + 5.0, 45.0)),
        "target_enabled": bool(ep.target_enabled),
        "hold_start_position": bool(ep.hold_spawn_position),
        "target_x_m": float(ep.target_x_m.nominal()),
        "target_y_m": float(ep.target_y_m.nominal()),
        "policy_onnx": "policy/best_policy.onnx",
    })
    out.setdefault("log_csv", "jetson_run_log.csv")
    return out


def build_jetson_package(cfg: AppConfig, out_dir: str, policy_onnx: Optional[str] = None,
                         policy_json: Optional[str] = None, classical_params=None) -> str:
    from classical_controller import controller_from_config, generate_controller_cpp
    from rl_onnx_cpp_engine import PolicySnapshot, generate_cpp, load_onnx_snapshot

    stamp = timestamp()
    tmp = tempfile.mkdtemp(prefix="bb8_pkg_")
    root = os.path.join(tmp, "bb8_jetson")
    src = os.path.join(_base_dir(), "deployment_jetson")
    shutil.copytree(src, root, ignore=shutil.ignore_patterns("build", "*.csv", "__pycache__", "policy"))
    shutil.copy2(os.path.join(_base_dir(), "classical_controller.py"), os.path.join(root, "classical_controller.py"))
    hw = hw_config_from_app(cfg, json.load(open(os.path.join(src, "robot_hw_config.json"))))
    files: Dict[str, str] = {}

    # --- RL policy -----------------------------------------------------------
    have_policy = bool(policy_onnx and os.path.isfile(policy_onnx))
    if have_policy:
        os.makedirs(os.path.join(root, "policy", "cpp"), exist_ok=True)
        shutil.copy2(policy_onnx, os.path.join(root, "policy", "best_policy.onnx"))
        snap = PolicySnapshot.load_json(policy_json) if policy_json and os.path.isfile(policy_json) \
            else load_onnx_snapshot(policy_onnx)
        if snap is not None:
            snap.save_json(os.path.join(root, "policy", "best_policy.json"))
            if snap.action_mode == "velocity":
                generate_cpp(snap, os.path.join(root, "policy", "cpp"))
    else:
        hw["policy_onnx"] = ""

    # --- classical controller (baseline / fallback) ---------------------------
    ctrl = controller_from_config(cfg, classical_params)
    ctrl.save_json(os.path.join(root, "classical_params.json"))
    generate_controller_cpp(ctrl, os.path.join(root, "classical", "cpp"),
                            steps_per_rad=cfg.robot.steps_per_rad)
    with open(os.path.join(root, "robot_hw_config.json"), "w") as f:
        json.dump(hw, f, indent=2)
    with open(os.path.join(root, "DEPLOY.md"), "w") as f:
        f.write(_deploy_readme(cfg, hw, have_policy))
    with open(os.path.join(root, "sim_config_snapshot.json"), "w") as f:
        f.write(cfg.to_json())

    os.makedirs(out_dir, exist_ok=True)
    zpath = os.path.join(out_dir, f"bb8_jetson_package_{stamp}.zip")
    with zipfile.ZipFile(zpath, "w", zipfile.ZIP_DEFLATED) as z:
        for dp, _, fns in os.walk(root):
            for fn in fns:
                full = os.path.join(dp, fn)
                z.write(full, os.path.relpath(full, tmp))
    shutil.rmtree(tmp, ignore_errors=True)
    return zpath


def _deploy_readme(cfg: AppConfig, hw: dict, have_policy: bool) -> str:
    rc = cfg.robot
    th = math.radians(rc.zenith_angle_deg)
    return f"""# BB-8 Jetson package ({timestamp()})

Generated for: ball {rc.ball_radius_m * 200:.0f} cm, wheels {rc.wheel_diameter_m * 1000:.0f} mm, zenith {rc.zenith_angle_deg:.1f} deg,
azimuths {rc.wheel_azimuths_deg}, control {rc.control_hz:.0f} Hz, max wheel speed {rc.stepper_max_speed_rads:.0f} rad/s,
{rc.tmc2208_microsteps} microsteps. Static load per wheel ~{cfg.robot.head_mass_kg * 9.81 / (3 * math.cos(th)):.1f} N.

**Check `robot_hw_config.json` wiring fields** (I2C addresses, UART ports, GPIO lines, direction signs)
before the first run - only geometry was generated.

## 1. Copy & install (on the Jetson)
```bash
unzip bb8_jetson_package_*.zip && cd bb8_jetson
pip3 install numpy smbus2 pyserial onnx      # + onnxruntime wheel for your JetPack
```

## 2. Bring-up tests (robot on a stand, motors may move!)
```bash
python3 jetson_control_loop.py --test signs          # IMU axis / encoder sign check (interactive)
python3 jetson_control_loop.py --test imu-noise      # 60 s still -> noise & drift numbers
python3 jetson_control_loop.py --test motor-step     # each motor: step response, latency
```
Enter the printed numbers in the desktop app: *Tools -> Real-world verification examples*.

## 3. First balancing with the classical controller (tether + kill switch!)
```bash
sudo chrt -f 80 python3 jetson_control_loop.py --controller classical
```

## 4. RL policy
{"```bash" + chr(10) + "sudo chrt -f 80 python3 jetson_control_loop.py --policy policy/best_policy.onnx" + chr(10) + "```" if have_policy else "_No trained policy was included in this package._"}

## 5. Hard real-time C++ runner
```bash
mkdir -p build && cd build
cmake .. -DPOLICY_DIR=../policy/cpp        # RL policy   (or ../classical/cpp for the classical controller)
make -j4 && sudo ./bb8_jetson_runner ../robot_hw_config.json
```
"""
